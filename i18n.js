/* Russian plural: 1 → form 0, 2–4 → form 1, 5+ → form 2 (with 11–14 exception) */
function pluralOf(n, key) {
  const f = I18N[key];
  if (!f) return key;
  const en = f.en, ru = f.ru;
  n = Math.abs(n);
  if (LANG === "ru" && ru) {
    const m10 = n % 10, m100 = n % 100;
    const i = (m10 === 1 && m100 !== 11) ? 0 : (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) ? 1 : 2;
    return ru[i];
  }
  return en[n === 1 ? 0 : 1];
}
